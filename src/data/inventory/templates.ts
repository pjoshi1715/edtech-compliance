import type { DataElement, ProductType } from '@/types'

// Helper to create a template data element with default values
function createTemplateElement(overrides: Partial<DataElement>): Omit<DataElement, 'id' | 'createdAt' | 'updatedAt' | 'riskLevel' | 'riskScore'> {
  return {
    name: '',
    category: 'pii',
    source: 'user_input',
    purposes: ['product_functionality'],
    storageLocation: 'aws',
    encryptionAtRest: 'yes',
    encryptionInTransit: 'yes',
    backupStrategy: 'automated',
    accessRoles: ['admins'],
    accessControlMethod: 'rbac',
    loggingEnabled: 'yes',
    mfaRequired: 'no',
    retentionPeriod: 'account_lifetime',
    deletionPolicy: 'soft_delete',
    userDeletionRights: 'can_delete',
    sharedWithThirdParties: false,
    thirdPartyRecipients: [],
    ...overrides,
  }
}

